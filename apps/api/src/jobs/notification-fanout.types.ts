/**
 * Bulk notices (a School broadcast, a waiver request to every member) queue
 * with this BullMQ priority. BullMQ always takes jobs with no priority first,
 * so a waitlist seat offer (60 minutes to claim), a cancelled class or a
 * payment notice is never stuck behind thousands of bulk ones. Stress test
 * round 4 (N1): 500 broadcasts and 500 waiver requests left ~270k jobs, about
 * 40 minutes, in front of a seat offer.
 */
export const BULK_NOTIFICATION_PRIORITY = 10;

/**
 * Shared payload shape for the `notification-fanout` queue — every producer
 * (WaiverSignatureRequestsProcessor today, more triggers in future phases)
 * and its one consumer (NotificationFanoutProcessor) import this instead of
 * each defining their own inline object shape, found on review to have
 * silently drifted from each other with no compiler check tying them
 * together.
 *
 * `notificationId` is REQUIRED, not generated by the consumer — every
 * producer must derive a stable, deterministic id from its own trigger
 * context (e.g. `waiver-${waiverId}-${userId}`), used as BOTH the BullMQ
 * `jobId` (queue-level dedup — re-enqueueing the same id while the original
 * job is still present/completed is a safe no-op) AND the Notification row's
 * own primary key (job-level retry safety — NotificationFanoutProcessor
 * upserts on this id, so a retried job attempt doesn't create a second row
 * for the same underlying event). See NotificationFanoutProcessor's own
 * header comment for the full reasoning.
 */
export interface NotificationFanoutJobData {
  notificationId: string;
  userId: string;
  title: string;
  body: string;
  type?: string;
  /** Set on a parent's copy of a child's notification (the child's userId) —
   * see NotificationFanoutProcessor. A copy is never copied on again. */
  guardianCopyOf?: string;
  /** Decision 355 — the School this is from (the fanout job looks up its
   * name for the label) and what clicking it opens. See the Notification
   * model's own comments. */
  schoolId?: string;
  targetType?: NotificationTargetType;
  targetId?: string;
  /** In the app's Notifications only: no push and no email (Decision 386:
   * an unplanned open mat, whose push alert is a student's opt-in). Copied
   * onto a parent's copy. */
  inAppOnly?: boolean;
}

/** Decision 355 — what a notification opens when clicked. CLASS and WAIVER
 * carry the item's id; PAYMENT, CANCELLATIONS and GRADING open a list page.
 * Decision 364 adds FRANCHISE (the Franchise's page) and SCHOOL (the School page). */
export type NotificationTargetType = 'CLASS' | 'WAIVER' | 'PAYMENT' | 'CANCELLATIONS' | 'GRADING' | 'FRANCHISE' | 'SCHOOL';
