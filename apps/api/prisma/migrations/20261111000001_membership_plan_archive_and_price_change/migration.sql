-- v1.2 backend backlog — two approved MembershipPlan features:
--
-- 1. Archive lifecycle state. `MembershipPlan.archivedAt` is the same single-
--    nullable-timestamp lifecycle-flag shape Franchise/School already
--    established for their own `archivedAt` (Decision 110, 20260956* purge
--    migration) — see schema.prisma's own header comment on this column for
--    why that convention was reused instead of a second boolean. No
--    `purgeAt`/`purgedAt` pair here — this is a single-entity archive, not
--    the whole-tenant 90-day offboarding cascade those two columns serve.
--
-- 2. Subscription price-change migrate-vs-grandfather prompt.
--    `MembershipPlan.stripeProductId`/`stripePriceId` persist a reusable
--    Stripe Product/Price once a price-change decision has been recorded
--    (see schema.prisma's own header comment) — `PaymentsService.subscribe()`'s
--    pre-existing throwaway-Product/inline-price_data path (Phase 9) is
--    untouched for any plan that never reaches this. `MembershipPlanPriceChange`
--    is the auditable decision log (one row per staff decision), with its
--    own RLS policy mirroring PaymentAccount's School-Owner-only read/write
--    shape (this is revenue-adjacent, Stripe-linkage data, not the broad
--    "any active RoleGrant holder" shape MembershipPlan's own catalog-read
--    policy uses) plus an ultm8_jobs ALL-commands policy (the MIGRATE
--    background job, running under ultm8_jobs, owns status/migratedCount/
--    failedCount/completedAt from PENDING onward — same shape
--    franchise_fee_charge_jobs_all already established for an analogous
--    job-owned row).
--
-- Additive-only (Decision 32) — no existing table/policy from any prior
-- migration is touched, except the one deliberately-scoped exception noted
-- below (membership_plan_discovery_read, widened via ALTER POLICY rather
-- than DROP+CREATE, since this is strictly narrowing what that policy
-- already admits, not loosening it).
--
-- Same provenance caveat as every prior migration in this repo: hand-
-- authored, not generated by `prisma migrate dev` — verified by applying it
-- directly against a real local Postgres in this session before trusting it
-- past a walking skeleton (see this PR's own description).

-- ============================================================================
-- 1. MembershipPlan — archive + persisted Stripe Product/Price columns.
-- ============================================================================

ALTER TABLE "MembershipPlan" ADD COLUMN "archivedAt" TIMESTAMP(3);
ALTER TABLE "MembershipPlan" ADD COLUMN "stripeProductId" TEXT;
ALTER TABLE "MembershipPlan" ADD COLUMN "stripePriceId" TEXT;

-- The Discovery-facing read (AcademiesService.findOne, ultm8_discovery) must
-- never show an archived plan to a browsing Student — same belt-and-
-- suspenders discipline the original `visible = true` clause was written
-- with (20260917000000_academies_discovery_module's own comment): the
-- row-level policy is what actually protects an archived plan if a future
-- query ever forgets AcademiesService's own app-layer `where` filter (updated
-- in this same PR to add `archivedAt: null` alongside `visible: true`).
-- `ALTER POLICY` (not DROP+CREATE) keeps this a pure narrowing of the
-- existing policy, not a redefinition from scratch.
ALTER POLICY "membership_plan_discovery_read" ON "MembershipPlan"
  USING ("MembershipPlan"."visible" = true AND "MembershipPlan"."archivedAt" IS NULL);

-- Postgres requires SELECT privilege on a column referenced by a row-security
-- USING clause even when the column is never part of the returned row (same
-- requirement that migration's own comment already documents for ORDER BY) —
-- additive GRANT, doesn't touch the existing column list.
GRANT SELECT ("archivedAt") ON "MembershipPlan" TO ultm8_discovery;

-- ============================================================================
-- 2. MembershipPlanPriceChange — new table.
-- ============================================================================

CREATE TYPE "MembershipPlanPriceChangeDecision" AS ENUM ('MIGRATE', 'GRANDFATHER');
CREATE TYPE "MembershipPlanPriceChangeStatus" AS ENUM ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED');

CREATE TABLE "MembershipPlanPriceChange" (
    "id" TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    "membershipPlanId" TEXT NOT NULL,
    "schoolId" TEXT NOT NULL,
    "decision" "MembershipPlanPriceChangeDecision" NOT NULL,
    "oldPrice" INTEGER NOT NULL,
    "newPrice" INTEGER NOT NULL,
    "oldCurrency" TEXT,
    "newCurrency" TEXT,
    "decidedById" TEXT NOT NULL,
    "status" "MembershipPlanPriceChangeStatus" NOT NULL DEFAULT 'PENDING',
    "affectedMembershipCount" INTEGER NOT NULL DEFAULT 0,
    "migratedCount" INTEGER NOT NULL DEFAULT 0,
    "failedCount" INTEGER NOT NULL DEFAULT 0,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "completedAt" TIMESTAMP(3),
    CONSTRAINT "MembershipPlanPriceChange_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "MembershipPlanPriceChange_membershipPlanId_fkey" FOREIGN KEY ("membershipPlanId") REFERENCES "MembershipPlan"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "MembershipPlanPriceChange_schoolId_fkey" FOREIGN KEY ("schoolId") REFERENCES "School"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "MembershipPlanPriceChange_decidedById_fkey" FOREIGN KEY ("decidedById") REFERENCES "User"("id") ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Composite indexes leading with the tenant column (Decision 30).
CREATE INDEX "MembershipPlanPriceChange_schoolId_idx" ON "MembershipPlanPriceChange"("schoolId");
CREATE INDEX "MembershipPlanPriceChange_membershipPlanId_idx" ON "MembershipPlanPriceChange"("membershipPlanId");

GRANT SELECT, INSERT, UPDATE, DELETE ON "MembershipPlanPriceChange" TO ultm8_app;

ALTER TABLE "MembershipPlanPriceChange" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "MembershipPlanPriceChange" FORCE ROW LEVEL SECURITY;

-- School Owner/Manager only — same narrower shape PaymentAccount's own
-- read policy would use if it needed row-scoping (this table is genuinely
-- School-scoped, unlike the singular-resource PaymentAccount), not
-- MembershipPlan's own broad "any active RoleGrant holder" catalog-read
-- shape: this is a Stripe-linkage/pricing-decision audit log, the same
-- revenue-adjacent sensitivity class as Transaction/Membership (Phase 9's
-- own documented reasoning for why those two deviate from MembershipPlan's
-- policy), not public-ish catalog data.
CREATE POLICY "membership_plan_price_change_tenant_isolation" ON "MembershipPlanPriceChange"
  USING (
    EXISTS (
      SELECT 1 FROM "RoleGrant" rg
      WHERE rg."schoolId" = "MembershipPlanPriceChange"."schoolId"
        AND rg."userId" = current_setting('app.current_user_id', true)
        AND rg."role" = 'SCHOOL_OWNER_MANAGER'
        AND rg."revokedAt" IS NULL
    )
  );

-- ultm8_jobs needs full read/write — the MIGRATE background job
-- (membership-plan-price-migration.processor.ts) is the only writer that
-- ever advances status PENDING -> PROCESSING -> COMPLETED/FAILED and sets
-- migratedCount/failedCount/completedAt, and it has no single caller to run
-- under (same class of job as franchise-fee-usage-reporting). Same
-- unrestricted-USING(true)-both-ways shape franchise_fee_charge_jobs_all
-- already established for an analogous job-owned row — neither job ever
-- removes a row, so DELETE being included here (same as that policy) is
-- harmless, not a capability either job actually exercises.
GRANT SELECT, INSERT, UPDATE, DELETE ON "MembershipPlanPriceChange" TO ultm8_jobs;
CREATE POLICY "membership_plan_price_change_jobs_all" ON "MembershipPlanPriceChange"
  TO ultm8_jobs
  USING (true)
  WITH CHECK (true);
