-- anywhere in this codebase yet (verified directly, not assumed). Drawn-signature
-- capture (Decision 74's own engineering follow-up) is also out of scope — this
-- migration models the confirmed baseline mechanism (typed full name) only.
--
-- Additive-only (Decision 32) — no existing table/policy from any prior migration
-- is touched.
--
-- Same provenance caveat as every prior migration in this repo: hand-authored, not
-- generated by `prisma migrate dev` (no reachable Postgres in this environment) —
