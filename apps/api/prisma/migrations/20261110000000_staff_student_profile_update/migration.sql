-- v1.2 backend backlog — Student Detail "Edit" gap: a Staff member (School
-- Owner/Manager, Branch Staff, or Instructor) editing a Student's own profile on
-- their behalf via the new `PATCH /schools/{schoolId}/students/{studentId}/profile`
-- (SchoolsService.updateStudentProfile, which delegates the actual write to
-- UsersService.updateProfileFor).
--
-- No schema change — additive RLS policy only (Decision 32's convention).
--
-- `user_self_or_shared_school` (20260902000000_init) is declared with no `FOR`
-- clause, so it defaults to `FOR ALL` — its WITH CHECK ("id" = caller) governs
-- UPDATE's new-row check today, same as INSERT's, and was deliberately written for
-- the registration-bootstrap case only (a brand-new row whose id equals the caller's
-- own current_user_id — see that policy's own comment). It was never meant to
-- authorize a caller writing a DIFFERENT User's row, so this is a second, narrower,
-- PERMISSIVE policy scoped to exactly `FOR UPDATE` rather than a loosening of that
-- one — Postgres OR-combines permissive policies for the same command (the same
-- mechanism `user_auth_lookup`'s own comment already documents for SELECT).
--
-- Re-derives, independently in SQL, the exact two facts
-- SchoolsService.updateStudentProfile already checks in the app layer before this is
-- ever reached (TenantAuthorizationService.assertStaffAtSchool — any active
-- SCHOOL_OWNER_MANAGER/BRANCH_STAFF/INSTRUCTOR RoleGrant at the School — and its own
-- active-STUDENT-RoleGrant-at-that-School check, the same shape
-- SchoolsService.setStudentHomeBranch already uses): defense-in-depth, per this
-- project's standing convention (see school_tenant_isolation et al.) — RLS is the
-- backstop, not a second place this is designed from scratch.
--
-- No ultm8_app GRANT change needed — ultm8_app already has whole-table UPDATE on
-- "User" since 20260902000000_init; only the missing RLS policy blocked this case.
--
-- Same provenance caveat as every prior migration in this repo: hand-authored, not
-- generated by `prisma migrate dev` — verify against a real Postgres run before
-- trusting this past a walking skeleton.
CREATE POLICY "user_staff_update_student_profile" ON "User"
  FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM "RoleGrant" staff
      JOIN "RoleGrant" student ON student."schoolId" = staff."schoolId"
      WHERE staff."userId" = current_setting('app.current_user_id', true)
        AND staff."role" IN ('SCHOOL_OWNER_MANAGER', 'BRANCH_STAFF', 'INSTRUCTOR')
        AND staff."revokedAt" IS NULL
        AND staff."schoolId" IS NOT NULL
        AND student."userId" = "User"."id"
        AND student."role" = 'STUDENT'
        AND student."revokedAt" IS NULL
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM "RoleGrant" staff
      JOIN "RoleGrant" student ON student."schoolId" = staff."schoolId"
      WHERE staff."userId" = current_setting('app.current_user_id', true)
        AND staff."role" IN ('SCHOOL_OWNER_MANAGER', 'BRANCH_STAFF', 'INSTRUCTOR')
        AND staff."revokedAt" IS NULL
        AND staff."schoolId" IS NOT NULL
        AND student."userId" = "User"."id"
        AND student."role" = 'STUDENT'
        AND student."revokedAt" IS NULL
    )
  );
