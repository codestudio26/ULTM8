-- Explicit join table (not Prisma's implicit many-to-many — see schema.prisma's
-- own comment on RankRequiredSkill for why). No schoolId of its own — RLS
-- delegates entirely to Rank/Skill's own policies via the FK join below, which is
-- safe here (unlike the earlier "avoid a join" reasoning above) because this
-- table carries no queryable data of its own beyond the two FKs themselves; a
-- caller can only ever reach a row here by already having Rank/Skill visibility.
