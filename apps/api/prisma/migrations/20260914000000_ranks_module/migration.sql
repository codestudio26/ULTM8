-- ============================================================================
-- StudentRank, StudentRankSkillStatus, PromotionEvent — FOUND ON THE PHASE 10b
-- VERIFICATION PASS, RESOLVED AS A DIRECT PRODUCT DECISION, RECORDED AS DECISION
-- 88 (docs/decisions/POST-SPEC-55-DECISION-LOG.md) — NOT LEFT TO GUESS: these
-- three carry one specific Student's own grading data (classesAttendedToward-
-- Checkpoint, per-skill sign-off status, rank-history) — the same class of "not
-- School-wide catalog data" concern Phase 9 already found for Membership/
-- Transaction (verified against this repo's own merged migration), and Phase
-- 10's WaiversModule (PR #7) applies the same way for WaiverSignature. Same
-- narrow shape: SCHOOL_OWNER_MANAGER RoleGrant
-- holder at the row's own schoolId gets full read/write; the row's own Student
-- (studentId = current_setting('app.current_user_id')) gets read/write of their
-- OWN rows only; no other role (BRANCH_STAFF, INSTRUCTOR included) gets any row
-- access at all.
--
-- Instructor/Staff functional access (checking a Student's rank for class
-- eligibility, the Grading Board) is NOT traded away for this — it's handled at
-- the APPLICATION layer exactly the way Phase 9 already built for GET
-- /students/{id}/membership-status: TenantAuthorizationService.assertStaffAtSchool()
-- authorizes the caller, then the underlying read runs under the TARGET
-- Student's own tenant context (which satisfies the self-only clause below), not
-- the caller's — never by broadening this policy to admit Instructor/Branch
-- Staff directly.
-- ============================================================================

-- currentRankId is ON DELETE RESTRICT, not this schema's usual CASCADE for a
-- required FK (e.g. Membership -> MembershipPlan) — deliberate: cascading a Rank
-- deletion into deleting every Student's own StudentRank row that currently
-- points to it would destroy real grading history as a side effect of a catalog
-- edit. No Rank-delete endpoint exists this phase anyway (matching the
-- established "general tenant offboarding is [UNRESOLVED]" pattern), so this is
-- moot in practice today — kept as the correct choice on principle regardless.
