-- ============================================================================
-- Discipline, Rank, RankStripeTier, Skill, RankRequiredSkill — a School's belt/
-- grading catalog. Public-visibility catalog data, not a per-Student record — RLS
-- shape matches Class/TimetableSlot/MembershipPlan/Waiver's own "any active
-- RoleGrant holder at the School" pattern, NOT StudentRank's narrower shape below
-- (see that table's own header comment for why those need a materially different
-- policy — same split Phase 9/10 already established between catalog tables and
-- per-Student records).
--
-- Rank, RankStripeTier, and Skill each carry their OWN denormalized schoolId
-- (not just disciplineId) — without it, Rank's RLS policy would need a join
-- through Discipline to reach RoleGrant, and RankStripeTier (Rank's own child)
-- would need two joins. Decision 30's "composite index leading with the tenant
-- column" principle assumes a direct tenant column on every RLS-scoped table.
-- ============================================================================

