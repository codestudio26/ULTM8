-- ============================================================================
-- Membership and Transaction — FOUND ON THE PHASE 9 VERIFICATION PASS, BEFORE BUILD:
-- these two must NOT reuse the "any active RoleGrant holder at the School" shape
-- above (or PaymentAccount's/Class's own). A Student holds their own STUDENT
-- RoleGrant at the School — the generic shape would let every Student, Instructor,
-- and Branch Staff at a School read every OTHER Student's Membership and Transaction
-- rows (purchases, balances, payment method, invoice amounts). That directly
-- contradicts Spec 55 §8.2's own confirmed statement: "Membership and Transaction are
-- genuinely School-wide, not Branch-scopable... Branch Staff gets no raw row access
-- to either — only a narrow, purpose-built membership-status-check endpoint." If
-- Branch Staff — who hold a real RoleGrant at the School — are explicitly denied raw
-- access, the generic any-active-grant policy cannot be the right shape here.
--
-- Required shape (matches the Phase 9 kickoff prompt §3b exactly): a
-- SCHOOL_OWNER_MANAGER RoleGrant holder at the row's own schoolId gets full read/write
-- (this is what powers GET /schools/{id}/transactions, MembershipPlan-adjacent
-- purchase-ledger visibility, and PATCH /transactions/{id}/confirm); OR the row's own
-- Student (studentId = current_setting('app.current_user_id')) gets read/write of
-- their OWN rows only (this is what GET /memberships/me and the purchase endpoint's
-- own INSERT — a Student creating their own pending Transaction/Membership — need to
-- work under RLS at all, not just what the service-layer query happens to filter by).
-- No other role gets any row access. FRANCHISE_OWNER visibility is deliberately NOT
-- added — Spec 55 never confirms a Franchise-level rollup for these two tables
-- (unlike PaymentAccount, which can literally belong to a Franchise), so adding that
-- clause by analogy would be inventing a business rule, not following one.
--
-- One combined ALL-commands policy, USING only (no separate WITH CHECK) — Postgres
-- uses the USING clause for WITH CHECK too when none is given, same shape this
-- schema already relies on elsewhere. The two permitted groups need both read AND
-- write here (SCHOOL_OWNER_MANAGER for the confirm-path UPDATE; the Student
-- themselves for the purchase-path INSERT), unlike PaymentAccount's USING-only
-- policy, which only ever needed to cover reads at the RLS layer (its writes are
-- narrower than "any grant holder" to begin with, gated entirely in application code).
-- ============================================================================

CREATE TABLE "Membership" (
    "id" TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    "studentId" TEXT NOT NULL,
    "membershipPlanId" TEXT NOT NULL,
    "schoolId" TEXT NOT NULL,
    "status" "MembershipStatus" NOT NULL DEFAULT 'ACTIVE',
    "startDate" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "frequency" "MembershipFrequency" NOT NULL,
    "classesRemaining" INTEGER,
    "expiryDate" TIMESTAMP(3),
    "scopedClassId" TEXT,
    "giftedById" TEXT,
    "stripeSubscriptionId" TEXT,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "Membership_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "Membership_studentId_fkey" FOREIGN KEY ("studentId") REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "Membership_membershipPlanId_fkey" FOREIGN KEY ("membershipPlanId") REFERENCES "MembershipPlan"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "Membership_schoolId_fkey" FOREIGN KEY ("schoolId") REFERENCES "School"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "Membership_scopedClassId_fkey" FOREIGN KEY ("scopedClassId") REFERENCES "Class"("id") ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT "Membership_giftedById_fkey" FOREIGN KEY ("giftedById") REFERENCES "User"("id") ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE UNIQUE INDEX "Membership_stripeSubscriptionId_key" ON "Membership"("stripeSubscriptionId");

-- Atomicity requirement, Spec 55 §11.5 (quoted): "a Student may not hold two
-- simultaneous Active general-access (Subscription/Weekly Pass) Memberships at the
-- same School... an atomic, transactionally-locked check". A partial unique index,
-- not an app-layer findFirst-then-create check — the same TOCTOU class of bug
-- already fixed once in this codebase for the webhook dedup race (Phase 8).
-- "General-access" is identified via classesRemaining IS NULL rather than joining to
-- MembershipPlan.type (a unique index can't express a cross-table join) — correct
-- per Spec 55 §6.1's own field description: classesRemaining is "set for Class Pack
-- / Friend Pass types ONLY", so Subscription/Weekly Pass Memberships always have it
-- NULL, and nothing else does except TRIAL_MEMBERSHIP. Broadening the DB constraint
-- to also cover TRIAL_MEMBERSHIP (not literally named in the quoted rule above) is a
-- deliberate, flagged generalization, not asserted as settled fact — the safer
-- direction to err given this guards real money/Stripe-Subscription-creation, and a
-- unique index can be relaxed later far more easily than a missing one can be added
-- without a backfill once real data exists.
CREATE UNIQUE INDEX "Membership_one_active_general_access_per_school" ON "Membership"("studentId", "schoolId")
  WHERE "status" = 'ACTIVE' AND "classesRemaining" IS NULL;

-- KNOWN LIMITATION, found on review, not fixed this phase (flagged, not silently
-- built around or ignored): Spec 55 §8/Decision 26 confirms Membership.status
-- expiry-by-date is "a live-computed predicate evaluated at every access/booking
-- check against the stored expiry date, not a scheduled batch flip" — so a
-- WEEKLY_PASS/TRIAL_MEMBERSHIP Membership past its expiryDate stays status='ACTIVE'
-- in storage indefinitely (by design — no job ever flips it, and Postgres partial-
-- index predicates can't reference a mutable now()-style expression to exclude it
-- here either). That means THIS index, keyed purely on the stored status column,
-- will incorrectly block a Student from purchasing a new general-access Membership
-- at the same School after their old one has genuinely expired by date but not yet
-- had its status column touched by anything. The clean fix is a lazy expire-on-
-- access step (the purchase attempt itself IS an "access check" per the same
-- Decision 26 language) immediately before each of the three Membership-creation
-- call sites (MembershipsService.createMembershipAndReturn, PaymentsService.
-- confirmTransaction, StripeWebhookProcessingProcessor.handlePaymentIntentSucceeded)
-- attempts its INSERT — flip any ACTIVE, classesRemaining-IS-NULL Membership for
-- this studentId+schoolId whose expiryDate has passed to EXPIRED first. Not
-- implemented across all three call sites this phase given the size of this PR
-- already; tracked here rather than silently shipped as if solved.

GRANT SELECT, INSERT, UPDATE, DELETE ON "Membership" TO ultm8_app;
CREATE INDEX "Membership_schoolId_idx" ON "Membership"("schoolId");
CREATE INDEX "Membership_studentId_idx" ON "Membership"("studentId");
CREATE INDEX "Membership_membershipPlanId_idx" ON "Membership"("membershipPlanId");

ALTER TABLE "Membership" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Membership" FORCE ROW LEVEL SECURITY;
CREATE POLICY "membership_school_staff_or_self" ON "Membership"
  USING (
    EXISTS (
      SELECT 1 FROM "RoleGrant" rg
      WHERE rg."schoolId" = "Membership"."schoolId"
        AND rg."role" = 'SCHOOL_OWNER_MANAGER'
        AND rg."userId" = current_setting('app.current_user_id', true)
        AND rg."revokedAt" IS NULL
    )
    OR "Membership"."studentId" = current_setting('app.current_user_id', true)
  );

-- ultm8_jobs: the stripe-webhook-processing job creates a Membership Active on
-- payment_intent.succeeded and Expires one on customer.subscription.deleted — no
-- caller/tenant context to run these under (a global Stripe webhook, not a
-- School-scoped or Student-scoped HTTP request), the exact situation ultm8_jobs
-- already exists for (PrismaJobsService's own header comment). SELECT is for the
-- Expire path's lookup-by-stripeSubscriptionId, not just INSERT/UPDATE's own
-- RETURNING — same reasoning class-occurrence-generation's Class-insert grant
-- documents, extended here to a genuine WHERE-clause read.
GRANT SELECT, INSERT, UPDATE ON "Membership" TO ultm8_jobs;
CREATE POLICY "membership_jobs_read" ON "Membership"
  FOR SELECT
  TO ultm8_jobs
  USING (true);
CREATE POLICY "membership_jobs_insert" ON "Membership"
  FOR INSERT
  TO ultm8_jobs
  WITH CHECK (true);
CREATE POLICY "membership_jobs_update" ON "Membership"
  FOR UPDATE
  TO ultm8_jobs
  USING (true)
  WITH CHECK (true);

