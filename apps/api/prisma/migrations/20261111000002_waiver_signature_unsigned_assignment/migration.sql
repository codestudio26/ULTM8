-- v1.2 backend backlog ("Waivers page", gap 2) / product-owner decision — closes
-- the "WaiverSignature has no concept of 'unsigned' today" gap: previously
-- WaiversService.sign() was the ONLY code path that ever created a row here, so a
-- row's mere existence meant "signed" (this table's own
-- `status WaiverSignatureStatus DEFAULT 'SIGNED'`), making "who hasn't signed yet"
-- impossible to answer. Approved: write an explicit Unsigned row at "assignment"
-- time instead of only at actual-signing time — see WaiverAssignmentService's own
-- header comment (apps/api/src/waivers/waiver-assignment.service.ts) for exactly
-- which two real, already-wired moments this codebase has for "assignment".
--
-- Relaxes four columns to nullable — an Unsigned "assignment" row has no signer, no
-- typed name/signature, and no real signed date yet; all four are populated only
-- once WaiversService.sign() actually runs. See schema.prisma's own WaiverSignature
-- header comment for the full account.
--
-- `signedDate` also loses its `DEFAULT CURRENT_TIMESTAMP` — a stored default here
-- would otherwise stamp a fabricated "signed date" on a row nobody has signed yet,
-- the exact "a row's mere existence implies signed" bug this migration exists to
-- fix. sign() now sets it explicitly (`new Date()`) on every row it actually signs,
-- so no existing (already-signed) row's value changes.
--
-- The pre-existing partial unique index
-- (WaiverSignature_one_non_expired_per_student_per_waiver, status != 'EXPIRED')
-- needs no change: it already covers UNSIGNED/PENDING rows exactly like SIGNED
-- ones, which is what makes sign() updating an existing Unsigned row in place
-- (rather than inserting a second row) the correct fix for the "don't silently
-- double-sign" rule once Unsigned rows are real — see WaiversService.sign()'s own
-- header comment.
--
-- No ultm8_app GRANT change needed — WaiverSignature already has a table-level
-- grant (20260913000000_waivers_module); relaxing a column's nullability needs no
-- GRANT of its own, same reasoning 20260928000000/20260930000000's own comments
-- already give for their own column additions.
--
-- Same provenance caveat as every prior migration in this repo: hand-authored, not
-- generated by `prisma migrate dev` (no reachable Postgres in this environment) —
-- verify with a real `prisma migrate diff`/`migrate dev` run before trusting this
-- past a walking skeleton.

